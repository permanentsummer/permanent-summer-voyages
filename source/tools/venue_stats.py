"""Builds source/vstats.js from the venue pages in docs/venues/.
Per retreat destination: number of venues, largest meeting room, largest hotel,
and two venue photos for destinations that have no photos of their own.
Venue names are never written: partners stay confidential."""
import os, re, json, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VEN = os.path.join(ROOT, "..", "docs", "venues")
MAP = {  # retreat slug -> venue cities ("X Area" is folded into "X"); "@Country" = whole country
 "algarve":["Algarve","Faro","Lagos","Carvoeiro","Vilamoura","Tavira"], "lisbonne":["Lisbon","Sintra","Estoril","Costa Da Caparica"],
 "ericeira":["Ericeira"], "porto":["Porto","Guimarães"], "madere":["Madeira"], "acores":["Azores"],
 "majorque":["Mallorca"], "barcelone":["Barcelona","Sitges"], "seville":["Seville"], "rome":["Rome"],
 "toscane":["Tuscany","Florence","Pisa"], "milan-come":["Milan","Bergamo","Stresa"], "pouilles":["Puglia"],
 "vienne":["Vienna"], "prague":["Prague"], "budapest":["Budapest"], "serbie":["Belgrade","Divčibare"],
 "croatie":["Split","Dubrovnik","Dalmatia","Sibenik","Trogir"], "istanbul":["Istanbul"], "georgie":["Tbilisi"],
 "marrakech":["Marrakech"], "taghazout":["Taghazout","Agadir","Region Sus-Masa-Draa"], "athenes":["Athens"],
 "crete":["Crete"], "peloponnese":["Isthmia"], "cracovie":["Krakow"], "ile-maurice":["@Mauritius"],
 "cascais":["Cascais"], "peniche":["Peniche"], "sesimbra":["Sesimbra","Setubal"], "madrid":["Madrid"],
 "costa-brava":["Catalonia","Costa Brava","Lloret de Mar","Tossa de Mar"], "malaga":["Malaga","Marbella","Ronda"],
 "valence":["Valencia"], "tenerife":["Tenerife"], "ibiza":["Ibiza"], "gran-canaria":["Gran Canaria"],
 "minorque":["Menorca"], "lanzarote":["Lanzarote"], "fuerteventura":["Fuerteventura"], "riviera-italienne":["Genoa"],
 "naples-amalfi":["Naples"], "sardaigne":["Sardinia"], "sicile":["Sicily","Palermo"], "bologne":["Bologna"],
 "thessalonique":["Thessaloniki"], "eubee":["Eretria"], "izmir":["Izmir"], "antalya":["Antalya"], "bodrum":["Bodrum"],
}
num = lambda s: int(re.sub(r"[^\d]", "", s) or 0)
venues = []
for d in sorted(os.listdir(VEN)):
    f = os.path.join(VEN, d, "index.html")
    if not os.path.exists(f): continue
    t = open(f, encoding="utf8").read()
    m = re.search(r"Venue proposal\s*/\s*([^<]+)", t)
    if not m: continue
    city, _, country = re.sub(r"\s+", " ", m.group(1)).strip().replace("&amp;", "&").rpartition(" · ")
    facts = {re.sub(r"<[^>]+>", "", s).strip().lower(): re.sub(r"<[^>]+>", "", b).strip() for b, s in re.findall(r"<b>(.*?)</b>\s*<small>(.*?)</small>", t)}
    imgs = list(dict.fromkeys(re.findall(r"https://media\.permanentsummervoyages\.com/venues/[^\"']+?\.webp", t)))
    venues.append(dict(city=re.sub(r"\s+(Area|Countryside)$", "", city.strip()), country=country.strip(),
                       rooms=num(facts.get("rooms", "")), cap=num(facts.get("meeting capacity", "")), imgs=imgs))
countries = {v["country"] for v in venues if v["country"] and v["country"][0].isupper()}
stats, rimg = {}, {}
for slug, cities in MAP.items():
    vs = [v for v in venues if (v["city"] in cities) or ("@" + v["country"] in cities)]
    if not vs: continue
    stats[slug] = {"n": len(vs), "cap": max(v["cap"] for v in vs), "rooms": max(v["rooms"] for v in vs)}
    pool = sorted([v for v in vs if len(v["imgs"]) >= 2], key=lambda v: (-len(v["imgs"]), v["imgs"][0]))
    if len(pool) >= 2: rimg[slug] = [pool[0]["imgs"][0], pool[1]["imgs"][0]]
    elif pool: rimg[slug] = pool[0]["imgs"][:2]
total = {"venues": len(venues), "countries": len(countries)}
js = ("/* Generated by tools/venue_stats.py from docs/venues — do not edit by hand. */\n"
      f"window.VTOTAL = {json.dumps(total)};\nwindow.VSTATS = {json.dumps(stats, ensure_ascii=False)};\n"
      f"window.RIMG = {json.dumps(rimg)};\n"
      "window.RETREATS.forEach(r => { if (!r.img && window.RIMG[r.s]) r.img = window.RIMG[r.s]; });\n")
open(os.path.join(ROOT, "vstats.js"), "w", encoding="utf8").write(js)
print(total, len(stats), "destinations with stats;", [s for s in MAP if s not in stats], "without")
